import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile, readdir } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import { PGlite } from "@electric-sql/pglite";

test("complete migration chain preserves existing teams, invitation-only access and private records, attachments and GOI comments", async () => {
  const db = new PGlite();
  try {
    await db.exec(`create schema auth;create table auth.users(id uuid primary key,raw_user_meta_data jsonb,email text,email_confirmed_at timestamptz);
      create role anon;create role authenticated;
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      grant usage on schema auth to anon,authenticated;grant execute on function auth.uid() to anon,authenticated;
      create schema storage;create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text references storage.buckets(id),name text,unique(bucket_id,name));
      alter table storage.objects enable row level security;grant usage on schema storage to anon,authenticated;grant select on storage.objects to anon;grant select,insert,delete on storage.objects to authenticated;`);
    const owner = randomUUID(), editor = randomUUID(), viewer = randomUUID(), outsider = randomUUID();
    const dir = new URL("../supabase/migrations/", import.meta.url);
    const files = (await readdir(dir)).filter(f => f.endsWith(".sql")).sort();
    const migrate = async (file: string) => db.exec((await readFile(new URL(file, dir), "utf8")).replace("create extension if not exists pgcrypto;", ""));
    for (const file of files.filter(f => f < "005")) await migrate(file);
    for (const id of [owner, editor, viewer, outsider]) await db.query("insert into auth.users(id,raw_user_meta_data) values($1,'{\"name\":\"Test\"}')", [id]);
    async function as(id: string | null) {
      await db.exec("reset role");
      await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id || ""]);
      await db.exec(id ? "set role authenticated" : "set role anon");
    }
    async function scalar<T = string>(sql: string, args: unknown[] = []) { return (await db.query<{ value: T }>(sql, args)).rows[0].value; }
    await as(owner);
    const w = await scalar("select create_workspace('Equipo original') as value");
    const p = await scalar("insert into records(workspace_id,kind,title,fields) values($1,'project','Proyecto','{\"north_star\":\"Compras\",\"posthog_project_id\":\"42\",\"posthog_host\":\"https://us.posthog.com/\"}') returning id as value", [w]);
    await db.exec("reset role");
    for (const file of files.filter(f => f >= "005")) await migrate(file);
    await as(owner);
    assert.equal(await scalar("select open_team_space() as value"), w);
    assert.equal(await scalar("select title as value from records where id=$1", [p]), "Proyecto");
    assert.equal(await scalar("select external_project_id as value from posthog_project_bindings where project_id=$1", [p]), "42");
    await assert.rejects(db.query("update posthog_project_bindings set external_project_id='99' where project_id=$1", [p]));
    await assert.rejects(db.query("select create_team('Otra empresa')"));
    const editorToken = await scalar("select create_invitation($1,'editor') as value", [w]);
    const viewerToken = await scalar("select create_invitation($1,'viewer') as value", [w]);
    await as(outsider);
    assert.equal(await scalar("select open_team_space() as value"), null);
    assert.equal((await db.query("select * from records")).rows.length, 0);
    assert.equal((await db.query("select * from posthog_project_bindings")).rows.length, 0);
    await assert.rejects(db.query("select create_team('Otro equipo')"));
    await as(null);
    const preview = await scalar<Record<string, unknown>>("select get_invitation_preview($1) as value", [editorToken]);
    assert.deepEqual(Object.keys(preview).sort(), ["expires_at", "role", "team_name"]);
    assert.equal(preview.team_name, "Equipo original");
    await as(editor);
    assert.equal(await scalar("select join_workspace($1) as value", [editorToken]), w);
    await assert.rejects(db.query("select join_workspace($1)", [editorToken]));
    async function record(kind: string, parent: string | null = null, fields = {}) {
      return scalar("insert into records(workspace_id,project_id,kind,title,parent_id,fields) values($1,$2,$3,$3,$4,$5) returning id as value", [w, p, kind, parent, JSON.stringify(fields)]);
    }
    await assert.rejects(record("goal"));
    const ns = await record("north_star");
    const goal = await record("goal", ns);
    const subgoal = await record("goal", goal);
    await assert.rejects(db.query("update records set parent_id=$1 where id=$2", [subgoal, goal]));
    const opportunity = await record("opportunity", goal);
    const idea = await record("idea", opportunity);
    const experiment = await record("experiment", idea, { posthog_experiment_id: "101", hypothesis: "Prueba", status: "obsolete", impact: 5 });
    const fields = await scalar<Record<string, unknown>>("select fields as value from records where id=$1", [experiment]);
    const code=await scalar("select code as value from experiment_specs where experiment_id=$1",[experiment]);
    assert.equal(code,'EXP-PROYECTO-0001');
    const second=await record('experiment');
    assert.equal(await scalar("select code as value from experiment_specs where experiment_id=$1",[second]),'EXP-PROYECTO-0002');
    await assert.rejects(db.query("update experiment_specs set code='FORGED' where experiment_id=$1",[experiment]));
    await assert.rejects(db.query("update experiment_specs set timezone='Invalid/Timezone' where experiment_id=$1",[experiment]));
    const variant=await scalar("insert into experiment_variants(workspace_id,project_id,experiment_id,label,is_control,created_by) values($1,$2,$3,'A',true,$4) returning id as value",[w,p,experiment,outsider]);
    assert.equal(await scalar("select created_by as value from experiment_variants where id=$1",[variant]),editor);
    await assert.rejects(db.query("insert into experiment_variants(workspace_id,project_id,experiment_id,label,is_control) values($1,$2,$3,'B',true)",[w,p,experiment]));
    await assert.rejects(db.query("insert into external_resources(workspace_id,project_id,experiment_id,variant_id,provider,resource_type,external_id) values($1,$2,$3,$4,'meta_ads','campaign','other')",[w,p,second,variant]));
    const resource=await scalar("insert into external_resources(workspace_id,project_id,experiment_id,variant_id,provider,resource_type,external_id) values($1,$2,$3,$4,'meta_ads','campaign','123') returning id as value",[w,p,experiment,variant]);
    const urlOnly=await scalar("insert into external_resources(workspace_id,project_id,experiment_id,provider,resource_type,external_url) values($1,$2,$3,'meta_ads','campaign','https://example.org/campaign') returning id as value",[w,p,experiment]);
    assert.ok(urlOnly);
    const measure="insert into metric_observations(workspace_id,project_id,experiment_id,resource_id,metric,value,unit,period_start,period_end,source) values($1,$2,$3,$4,'clicks',$5,$6,'2026-10-01','2026-10-07',$7)";
    await assert.rejects(db.query(measure,[w,p,experiment,resource,10,'count','api']));
    await assert.rejects(db.query(measure,[w,p,experiment,resource,1.5,'count','manual']));
    await assert.rejects(db.query(measure,[w,p,experiment,resource,1.5,'ratio','manual']));
    await db.query(measure,[w,p,experiment,resource,10,'count','manual']);
    await db.query(measure+" on conflict(resource_id,metric,period_start,period_end) do update set value=excluded.value,source=excluded.source",[w,p,experiment,resource,12,'count','csv']);
    assert.equal(await scalar<number>("select count(*)::int as value from metric_observations"),1);
    assert.equal(await scalar<number>("select count(*)::int as value from audit_log where action like 'metric_observations:%'"),2);
    await assert.rejects(db.query("update experiment_variants set experiment_id=$1 where id=$2",[second,variant]));
    const request=randomUUID();
    assert.equal(Number(await scalar("select reserve_ai_preparation($1,$2) as value",[w,request])),0.03);
    await assert.rejects(db.query("select reserve_ai_preparation($1,$2)",[w,request]),/ya fue procesada/);
    await assert.rejects(db.query("select reserve_ai_preparation($1,$2)",[w,randomUUID()]),/15 segundos/);
    await assert.rejects(db.query("insert into ai_preparation_usage(request_id,workspace_id,user_id,reserved_usd) values($1,$2,$3,0)",[randomUUID(),w,editor]));
    await db.exec('reset role');
    await db.query("update ai_preparation_usage set created_at=now()-interval '1 minute' where request_id=$1",[request]);
    await db.query("insert into ai_preparation_usage(request_id,workspace_id,user_id,created_at) select gen_random_uuid(),$1,$2,now()-interval '1 minute' from generate_series(1,165)",[w,editor]);
    await as(editor);
    await assert.rejects(db.query("select reserve_ai_preparation($1,$2)",[w,randomUUID()]),/5 USD/);
    // A second real workspace; membership in both does not permit mixing references.
    await db.exec('reset role');
    const beta=randomUUID(); await db.query("insert into auth.users(id,raw_user_meta_data) values($1,'{}')",[beta]);
    const w2=await scalar("insert into workspaces(name,created_by) values('Other',$1) returning id as value",[beta]);
    await db.query("insert into members(workspace_id,user_id,role) values($1,$2,'owner'),($1,$3,'editor')",[w2,beta,editor]);
    await as(beta);
    const p2=await scalar("insert into records(workspace_id,kind,title) values($1,'project','Private') returning id as value",[w2]);
    const e2=await scalar("insert into records(workspace_id,project_id,kind,title) values($1,$2,'experiment','Private') returning id as value",[w2,p2]);
    await as(editor);
    await assert.rejects(db.query("insert into external_resources(workspace_id,project_id,experiment_id,variant_id,provider,resource_type,external_id) values($1,$2,$3,$4,'meta_ads','campaign','cross')",[w2,p2,e2,variant]));
    await as(owner);
    assert.equal((await db.query("select * from experiment_specs where workspace_id=$1",[w2])).rows.length,0);
    await assert.rejects(db.query("select reserve_ai_preparation($1,$2)",[w2,randomUUID()]));
    await db.exec('reset role'); await db.query("delete from members where workspace_id=$1 and user_id=$2",[w2,editor]);
    await as(editor);
    await db.query("delete from records where id=$1",[second]);
    assert.equal(fields.posthog_experiment_id, "101");assert.equal(fields.status, undefined);
    const plan={goal:'traffic',destination:'https://greenhunt.net/',audience:'Stooping',location:'Nueva York',daily_budget:10,currency:'USD',duration_days:7,variants:[{label:'A',description:'Gratis',headline:'Muebles',body:'Descubre objetos',call_to_action:'Ver más',allocation:50},{label:'B',description:'Circular',headline:'Reutiliza',body:'Economía circular',call_to_action:'Ver más',allocation:50}]};
    const preparation={id:experiment,workspace_id:w,project_id:p,title:'Preparado',owner_id:null,parent_id:idea,related_id:null,fields:{...fields,channel:'meta_ads',start:'2026-10-11',execution_config:JSON.stringify(plan)}};
    const saved=await scalar<{updated_at:string}>("select to_jsonb(r) as value from save_experiment_preparation($1,(select updated_at from records where id=$2)) r",[JSON.stringify(preparation),experiment]);
    assert.equal(await scalar<number>('select budget::float as value from experiment_specs where experiment_id=$1',[experiment]),10);
    assert.equal(await scalar<string>('select planned_end::text as value from experiment_specs where experiment_id=$1',[experiment]),'2026-10-17');
    assert.equal(await scalar<string>("select id as value from experiment_variants where experiment_id=$1 and label='A'",[experiment]),variant);
    assert.equal(await scalar<number>('select count(*)::int as value from experiment_variants where experiment_id=$1',[experiment]),2);
    await db.query('update experiment_specs set budget=12 where experiment_id=$1',[experiment]);
    const resaved=await scalar<{updated_at:string}>("select to_jsonb(r) as value from save_experiment_preparation($1,$2) r",[JSON.stringify(preparation),saved.updated_at]);
    assert.equal(await scalar<number>('select budget::float as value from experiment_specs where experiment_id=$1',[experiment]),12);
    await assert.rejects(db.query('select save_experiment_preparation($1,$2)',[JSON.stringify(preparation),saved.updated_at]));
    await assert.rejects(db.query('select save_experiment_preparation($1,$2)',[JSON.stringify({...preparation,title:'Must roll back',fields:{...preparation.fields,execution_config:JSON.stringify({...plan,variants:[plan.variants[0],plan.variants[0]]})}}),resaved.updated_at]));
    assert.equal(await scalar<string>('select title as value from records where id=$1',[experiment]),'Preparado');
    const learning = await record("learning", experiment);
    const comment = await scalar("insert into record_comments(workspace_id,record_id,author_id,author_name,body) values($1,$2,$3,'Forged','Evidencia') returning id as value", [w, goal, outsider]);
    assert.equal(await scalar("select author_id as value from record_comments where id=$1", [comment]), editor);
    await assert.rejects(db.query("insert into record_comments(workspace_id,record_id,author_id,author_name,body) values($1,$2,$3,'Test',' ')", [w, goal, editor]));
    const attachmentId = randomUUID(), path = `${w}/${learning}/${attachmentId}.png`;
    await db.query("insert into record_attachments(id,workspace_id,record_id,name,kind,storage_path,mime_type,size) values($1,$2,$3,'Private','image',$4,'image/png',100)", [attachmentId, w, learning, path]);
    await db.query("insert into storage.objects(bucket_id,name) values('record-attachments',$1)", [path]);
    await as(null);
    assert.equal(await scalar("select get_public_preview() as value"), null);
    await assert.rejects(db.query("select stamp_record_comment_identity()"), /permission denied/);
    assert.equal((await db.query("select * from storage.objects")).rows.length, 0);
    await assert.rejects(db.query("select * from record_comments"));
    await as(viewer);
    await db.query("select join_workspace($1)", [viewerToken]);
    await assert.rejects(db.query('select save_experiment_preparation($1,$2)',[JSON.stringify(preparation),resaved.updated_at]));
    assert.equal((await db.query('select * from experiment_specs')).rows.length,1);
    assert.equal((await db.query('select * from metric_observations')).rows.length,1);
    assert.equal((await db.query("update experiment_specs set budget=10 returning experiment_id")).rows.length,0);
    await assert.rejects(db.query("insert into experiment_variants(workspace_id,project_id,experiment_id,label) values($1,$2,$3,'Viewer')",[w,p,experiment]));
    assert.equal((await db.query('delete from metric_observations returning id')).rows.length,0);
    await assert.rejects(db.query('select reserve_ai_preparation($1,$2)',[w,randomUUID()]));
    assert.equal((await db.query("select * from record_comments")).rows.length, 1);
    assert.equal((await db.query("select * from storage.objects")).rows.length, 1);
    await assert.rejects(db.query("insert into record_comments(workspace_id,record_id,author_id,author_name,body) values($1,$2,$3,'Test','No')", [w, goal, viewer]));
    assert.equal((await db.query("delete from record_attachments where id=$1 returning id", [attachmentId])).rows.length, 0);
    assert.equal((await db.query("delete from records where id=$1 returning id", [experiment])).rows.length, 0);
    await as(outsider);
    assert.equal((await db.query("select * from record_comments")).rows.length, 0);
    assert.equal((await db.query("select * from record_attachments")).rows.length, 0);
    // A confirmed account is not a team member until an administrator explicitly provisions it.
    await db.exec("reset role");
    const administrator = randomUUID();
    await db.query("insert into auth.users(id,raw_user_meta_data,email,email_confirmed_at) values($1,'{}','Admin@Example.org',now())", [administrator]);
    const repair = await readFile(new URL("../scripts/restore-team-owner.sql", import.meta.url), "utf8");
    await as(administrator);
    assert.equal(await scalar("select open_team_space() as value"), null);
    await assert.rejects(db.exec(repair.replaceAll("ADMINISTRATOR_EMAIL", "admin@example.org")));
    await db.exec("rollback;reset role");
    await assert.rejects(db.exec(repair.replaceAll("ADMINISTRATOR_EMAIL", "missing@example.org")));
    await db.exec("rollback;reset role");
    await db.query("insert into auth.users(id,raw_user_meta_data,email) values($1,'{}','unconfirmed@example.org')", [randomUUID()]);
    await assert.rejects(db.exec(repair.replaceAll("ADMINISTRATOR_EMAIL", "unconfirmed@example.org")));
    await db.exec("rollback;reset role");
    const existingRecords = await scalar<number>("select count(*)::int as value from records");
    const existingMembers = await scalar<number>("select count(*)::int as value from members");
    await db.exec(repair.replaceAll("ADMINISTRATOR_EMAIL", "admin@example.org"));
    await db.exec(repair.replaceAll("ADMINISTRATOR_EMAIL", "admin@example.org"));
    assert.equal(await scalar<number>("select count(*)::int as value from records"), existingRecords);
    assert.equal(await scalar<number>("select count(*)::int as value from members"), existingMembers + 1);
    await as(administrator);
    assert.equal(await scalar("select open_team_space() as value"), w);
    assert.equal(await scalar("select member_role($1) as value", [w]), "owner");
    assert.equal(await scalar("select title as value from records where id=$1", [p]), "Proyecto");
    await as(outsider);
    assert.equal(await scalar("select open_team_space() as value"), null);
    await as(owner);
    await db.query("delete from records where workspace_id=$1 and project_id=$2", [w, p]);
    await db.query("delete from records where id=$1", [p]);
    assert.equal((await db.query("select * from record_comments")).rows.length, 0);
    assert.equal((await db.query("select * from record_attachments")).rows.length, 0);
    assert.equal(await scalar("select storage_path as value from attachment_deletions"), path);
    await db.query("select remove_member($1,$2)", [w, editor]);
    await as(editor);
    assert.equal(await scalar("select open_team_space() as value"), null);
    assert.equal((await db.query("select * from workspaces")).rows.length, 0);
  } finally { await db.close(); }
});
